//! fi.rs — fault-injection campaign generation.
//!
//! Turns a ranked signal queue into a runnable differential campaign against a
//! real module:
//!
//!   * the module is instantiated twice, golden and faulted, in one model, so
//!     both see identical stimulus every cycle and any divergence is
//!     attributable to the fault alone;
//!   * stimulus is pseudo-random and seeded — a differential test does not
//!     require protocol-valid stimulus, because both instances receive the same
//!     (possibly nonsense) values, so the comparison stays controlled;
//!   * the fault is one assignment to one internal net, addressed by the
//!     flattened name Verilator exposes under `--public-flat-rw`;
//!   * the oracle reports a finding only when an observable diverges AND every
//!     detection signal agrees — divergence alone is noise, silence alone is
//!     trivial.
//!
//! Verilator 4.x has no `force`/`release`, but `--public-flat-rw` makes internal
//! nets assignable, which is all a fault campaign needs.

use crate::harness::{parse_ports, Dir, Port};

/// Names that mark a signal as the design's own detection path. Used only to
/// decide whether a divergence was reported, never to decide what to fault.
fn is_detection_signal(name: &str) -> bool {
    let n = name.to_ascii_lowercase();
    n.contains("err")
        || n.contains("fault")
        || n.contains("alert")
        || n.contains("intr")
        || n.contains("fatal")
        || n.contains("intg")
        || n.contains("invalid")
}

/// Simple scalar/vector ports we can randomise generically. Struct/interface
/// typed ports are tied off instead: assigning a random value to an arbitrary
/// packed struct is not expressible generically, and tying them off keeps both
/// instances identical, which is what the differential needs.
fn is_simple(p: &Port) -> bool {
    let t = p.ty.trim();
    !t.contains("::") && !t.contains("_t ") && !t.ends_with("_t")
}

pub struct FiTb {
    pub tb: String,
    pub observables: Vec<String>,
    pub stim_ports: Vec<String>,
}

/// Generate the dual-instance fault-injection testbench for `module`.
pub fn generate_tb(module: &str, top_src: &str, seed: u32) -> Result<FiTb, String> {
    let ports = parse_ports(top_src, module)?;
    if !ports.iter().any(|p| p.is_clock_or_reset()) && !ports.iter().any(|p| p.name == "clk_i") {
        return Err(format!("{module}: no clk_i port"));
    }

    let simple_inputs: Vec<&Port> = ports
        .iter()
        .filter(|p| p.dir == Dir::In && !p.is_clock_or_reset() && is_simple(p))
        .collect();
    let simple_outputs: Vec<&Port> = ports
        .iter()
        .filter(|p| p.dir == Dir::Out && is_simple(p))
        .collect();
    let complex_inputs: Vec<&Port> = ports
        .iter()
        .filter(|p| p.dir == Dir::In && !p.is_clock_or_reset() && !is_simple(p))
        .collect();

    let mut s = String::new();
    s.push_str(&format!(
        "// Generated by rtlsec — differential fault-injection harness for `{module}`.\n\
         // Golden and faulted instances receive identical stimulus; the fault is\n\
         // applied to the faulted instance's internals from the C++ driver.\n\
         `timescale 1ns/1ps\n"
    ));
    // Observables are declared as TOP-LEVEL OUTPUT PORTS. A top-module port is
    // always retained and is a member of the model class, so the C++ driver can
    // read it directly. An internal wire is removed entirely when nothing reads
    // it -- and the logic driving it goes with it, silently freezing the
    // observable -- and when it does survive it lives under the flattened root
    // path rather than on the model.
    s.push_str(&format!("module tb_fi_{module} (\n  input logic clk"));
    for p in &simple_outputs {
        s.push_str(&format!(
            ",\n  output logic obs_{0}_g,\n  output logic obs_{0}_f",
            p.name
        ));
    }
    s.push_str("\n);\n");
    s.push_str(&format!(
        "  int unsigned cyc = 0;\n\
         \x20 int unsigned CYCLES = 4000;\n\
         \x20 logic rst_ni = 1'b0;\n\n\
         \x20 // Seeded stimulus LFSR: identical values reach both instances.\n\
         \x20 logic [63:0] lfsr_q = 64'h{seed:016x};\n\
         \x20 always_ff @(posedge clk) begin\n\
         \x20   lfsr_q <= {{lfsr_q[62:0], lfsr_q[63] ^ lfsr_q[62] ^ lfsr_q[60] ^ lfsr_q[59]}};\n\
         \x20   cyc <= cyc + 1;\n\
         \x20   if (cyc == 8) rst_ni <= 1'b1;\n\
         \x20   if (cyc > CYCLES) $finish;\n\
         \x20 end\n\n"
    ));

    for p in &simple_inputs {
        s.push_str(&format!("  logic {}_s;\n", p.name));
    }
    for p in &complex_inputs {
        s.push_str(&format!("  logic {}_s;\n", p.name));
    }
    s.push('\n');

    // stimulus nets
    for p in &simple_inputs {
        s.push_str(&format!(
            "  assign {}_s = lfsr_q[{}:0];\n",
            p.name,
            if p.ty.contains('[') { 31 } else { 0 }
        ));
    }

    for (inst, tag) in [("u_golden", "g"), ("u_fault", "f")] {
        s.push_str(&format!("  {module} {inst} (\n"));
        let mut conns: Vec<String> = Vec::new();
        for p in &ports {
            if p.name == "clk_i" {
                conns.push(".clk_i(clk)".into());
            } else if p.is_clock_or_reset() {
                conns.push(format!(".{}(rst_ni)", p.name));
            } else if p.dir == Dir::In {
                if is_simple(p) {
                    conns.push(format!(".{0}({0}_s)", p.name));
                } else {
                    conns.push(format!(".{0}('0)", p.name));
                }
            } else if p.dir == Dir::Out && is_simple(p) {
                conns.push(format!(".{0}(obs_{0}_{tag})", p.name));
            } else {
                conns.push(format!(".{0}()", p.name));
            }
        }
        s.push_str(&conns.join(",\n    "));
        s.push_str("\n  );\n\n");
    }
    s.push_str("endmodule\n");

    Ok(FiTb {
        tb: s,
        observables: simple_outputs.iter().map(|p| p.name.clone()).collect(),
        stim_ports: simple_inputs.iter().map(|p| p.name.clone()).collect(),
    })
}

/// Map ranked signal names to the flattened member names Verilator generates.
/// `a.b.c` flattens to `a__DOT__b__DOT__c`; we confirm each against the header
/// text rather than assuming the mangling held.
pub fn discover_flat_names(header: &str, targets: &[String], instance: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for t in targets {
        // the signal name as it appears in the header, under the faulted tree
        // (bits are auto-generated into the decl, so the [..] index may vary)
        let flat = format!("{}__DOT__{}", instance, t);
        if let Some(rest) = header.split(&flat).nth(1) {
            // take the identifier up to the first non-identifier char
            let end = rest
                .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .unwrap_or(0);
            let full = format!("{}{}", flat, &rest[..end]);
            out.push((t.clone(), full));
        }
    }
    out
}

/// Find which ranked signals are exposed as members of the DUT class.
///
/// Under the per-signal `public_flat_rw` metacomment the signal becomes a
/// plainly named member of the module's own class (found in the submodule
/// header), rather than a mangled member of the root class. Whole-word
/// matching against that header is therefore the correct test, so that
/// `lock_q` does not match a longer name such as `lock_q2`.
///
/// Returns `(signal, member)` pairs; for this access form the member name is
/// the signal name itself.
pub fn discover_members(header: &str, targets: &[String]) -> Vec<(String, String)> {
    let bytes = header.as_bytes();
    let mut out = Vec::new();
    for t in targets {
        let mut hit = false;
        let mut from = 0usize;
        while let Some(pos) = header[from..].find(t.as_str()) {
            let abs = from + pos;
            let before_ok = abs == 0
                || !(bytes[abs - 1].is_ascii_alphanumeric() || bytes[abs - 1] == b'_');
            let end = abs + t.len();
            let after_ok =
                end >= bytes.len() || !(bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_');
            if before_ok && after_ok {
                hit = true;
                break;
            }
            from = abs + 1;
        }
        if hit {
            out.push((t.clone(), t.clone()));
        }
    }
    out
}

/// Find signals the patcher rewrote into a force-mux, returning
/// `(signal, force_variable)` pairs.
///
/// Marking a net with the metacomment does not make it addressable — Verilator
/// folds nets into their consumers, so only ~11 of 142 marked signals ever
/// appeared as members. The patcher therefore rewrites a single-driver net's
/// driver into `sel ? val : expr` over two public variables. Those variables do
/// become members, so a signal is forceable whenever both are present, even
/// though the signal itself is not.
pub fn discover_mux_targets(header: &str, targets: &[String]) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for t in targets {
        let val_needle = format!("rtlsec_fi_val_{t}");
        // The injected variable may sit inside an inlined submodule, in which
        // case Verilator flattens it to `u_<sub>__DOT__rtlsec_fi_val_<sig>`.
        // Match it as a suffix of a C++ identifier and keep the whole token,
        // because that is the name the driver must dereference.
        if let Some(full_val) = full_ident_suffix(header, &val_needle) {
            let sel_needle = full_val.replace("rtlsec_fi_val_", "rtlsec_fi_sel_");
            if contains_word(header, &sel_needle) {
                out.push((t.clone(), full_val));
            }
        }
    }
    out
}

/// Find `needle` as the suffix of a C++ identifier and return that whole
/// identifier (e.g. needle `rtlsec_fi_val_x` -> `u_core__DOT__rtlsec_fi_val_x`).
/// Returns None if `needle` only appears inside a longer identifier.
fn full_ident_suffix(hay: &str, needle: &str) -> Option<String> {
    let b = hay.as_bytes();
    let mut from = 0usize;
    while let Some(pos) = hay[from..].find(needle) {
        let abs = from + pos;
        let end = abs + needle.len();
        let at_end = end >= b.len() || !(b[end].is_ascii_alphanumeric() || b[end] == b'_');
        if at_end {
            let mut start = abs;
            while start > 0 && (b[start - 1].is_ascii_alphanumeric() || b[start - 1] == b'_') {
                start -= 1;
            }
            return Some(hay[start..end].to_string());
        }
        from = abs + 1;
    }
    None
}

/// Resolve a testbench-level observable wire to the member name Verilator
/// actually generated, or None if the wire does not exist in the model.
///
/// Two ways a wire can go missing: it may be privatised (gaining a `__PVT__`
/// prefix), or Verilator may eliminate it entirely because nothing in the
/// testbench reads it. An absent observable must be dropped rather than
/// compared, or the driver will not compile. Note the plain form is not a
/// substring of the privatised form (`__DOT__` is followed by `__PVT__`), so
/// testing the plain form first is safe.
pub fn resolve_obsw(header: &str, tb_top: &str, name: &str) -> Option<String> {
    let plain = format!("{tb_top}__DOT__{name}");
    if header.contains(&plain) {
        return Some(name.to_string());
    }
    let pvt = format!("{tb_top}__DOT____PVT__{name}");
    if header.contains(&pvt) {
        return Some(format!("__PVT__{name}"));
    }
    None
}

/// Whole-word test: `needle` must not be part of a longer identifier.
fn contains_word(hay: &str, needle: &str) -> bool {
    let bytes = hay.as_bytes();
    let mut from = 0usize;
    while let Some(pos) = hay[from..].find(needle) {
        let abs = from + pos;
        let before_ok =
            abs == 0 || !(bytes[abs - 1].is_ascii_alphanumeric() || bytes[abs - 1] == b'_');
        let end = abs + needle.len();
        let after_ok =
            end >= bytes.len() || !(bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_');
        if before_ok && after_ok {
            return true;
        }
        from = abs + 1;
    }
    false
}

/// Resolve a DUT port to the member name of its generated class.
///
/// Module ports that are not consumed at the top level carry a `__PVT__`
/// prefix, and the driver must use the name as generated.
pub fn resolve_member(header: &str, name: &str) -> Option<String> {
    if contains_word(header, name) {
        return Some(name.to_string());
    }
    let pvt = format!("__PVT__{name}");
    if contains_word(header, &pvt) {
        return Some(pvt);
    }
    None
}

/// Names of the module's INPUT ports, parsed from the generated class header.
///
/// Fault targets must exclude these. Forcing an input port corrupts the
/// stimulus rather than injecting a fault into the design's own state: it
/// trivially changes behaviour, and the design never had a chance to notice
/// anything, so such runs flood the oracle with meaningless "silent
/// divergences". Verilator labels direction in the header (VL_IN* vs VL_OUT*),
/// so this is exact rather than a guess.
pub fn input_ports(header: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in header.lines() {
        let l = line.trim();
        if !l.starts_with("VL_IN") {
            continue;
        }
        if let Some(open) = l.find('(') {
            if let Some(comma) = l[open..].find(',') {
                let name = l[open + 1..open + comma].trim();
                if !name.is_empty() {
                    out.push(name.trim_start_matches("__PVT__").to_string());
                }
            }
        }
    }
    out
}

/// True if the harness exposes `name` as a PAIRED top-level witness port
/// (`obs_<base>_g` / `obs_<base>_f`).
///
/// The oracle must compare these rather than DUT class members. Verilator
/// inlines a DUT port into the net that consumes it and can leave the class
/// member stale, so a member comparison reports divergence with no fault
/// injected - it is comparing a live signal in one instance against a dead one
/// in the other. A module-interface port is always retained and always driven.
/// A `__PVT__` prefix on the member name is a Verilator artifact and is
/// stripped, since the harness drives the port from the testbench net.
pub fn witness_port(model_header: &str, name: &str) -> Option<String> {
    let base = name.trim_start_matches("__PVT__");
    if model_header.contains(&format!("obs_{base}_g")) {
        Some(base.to_string())
    } else {
        None
    }
}

/// Generate the C++ campaign driver.
///
/// `targets` are (ranked signal name, flattened member name) pairs for the
/// faulted instance. `observables` are the testbench's compared nets. The
/// oracle flags a finding only when an observable diverges while every
/// detection-pattern observable agrees.
pub fn generate_cpp(
    model: &str,
    tb_top: &str,
    targets: &[(String, String)],
    observables: &[String],
    start_cycle: u32,
    fault_cycles: u32,
) -> String {
    // The DUT module is the testbench top minus the tb_fi_ prefix. Its
    // generated class {model}_{dut} must be included, otherwise the instance
    // pointers below are an incomplete type and the driver will not compile.
    let dut = tb_top.strip_prefix("tb_fi_").unwrap_or(tb_top);
    let mut s = String::new();

    s.push_str(&format!(
        "// Generated by rtlsec - differential fault-injection driver for {model}.\n"
    ));
    s.push_str(&format!("#include \"{model}.h\"\n"));
    s.push_str(&format!("#include \"{model}___024root.h\"\n"));
    s.push_str(&format!("#include \"{model}_{dut}.h\"\n"));
    s.push_str("#include \"verilated.h\"\n");
    s.push_str("#include <cstdio>\n");
    s.push_str("#include <cstdlib>\n");
    s.push_str("#include <cstring>\n");
    s.push_str("#include <string>\n");
    s.push_str("#include <set>\n\n");

    s.push_str("static const char* TARGETS[] = {\n");
    for (name, _) in targets {
        s.push_str(&format!("    \"{name}\",\n"));
    }
    s.push_str("};\n");
    s.push_str(&format!(
        "static const int N_TARGETS = {};\n\n",
        targets.len()
    ));

    // Observables split into security-relevant outputs and the
    // error/alert/status path. A fault is interesting only when the first
    // group moves and the second does not.
    let obs: Vec<&String> = observables
        .iter()
        .filter(|o| !is_detection_signal(o))
        .collect();
    let det: Vec<&String> = observables
        .iter()
        .filter(|o| is_detection_signal(o))
        .collect();

    s.push_str("int main(int argc, char** argv) {\n");
    s.push_str("    Verilated::commandArgs(argc, argv);\n");
    s.push_str("    std::string want;\n");
    s.push_str("    long start_cycle = -1, ncycles = -1;\n");
    s.push_str("    bool probe = false;\n");
    s.push_str("    bool contract = false;\n");
    s.push_str("    std::string cport_err, cport_act;\n");
    s.push_str("    for (int i = 1; i < argc; i++) {\n");
    s.push_str("        if (!std::strncmp(argv[i], \"+signal=\", 8)) want = argv[i] + 8;\n");
    s.push_str("        else if (!std::strncmp(argv[i], \"+cycle=\", 7)) start_cycle = std::atol(argv[i] + 7);\n");
    s.push_str("        else if (!std::strncmp(argv[i], \"+for=\", 5)) ncycles = std::atol(argv[i] + 5);\n");
    s.push_str("        else if (!std::strcmp(argv[i], \"+probe\")) probe = true;\n");
    s.push_str("        else if (!std::strncmp(argv[i], \"+contract=\", 10)) { contract = true; std::string a = argv[i] + 10; auto cm = a.find(','); if (cm != std::string::npos) { cport_err = a.substr(0, cm); cport_act = a.substr(cm + 1); } }\n");
    s.push_str("    }\n");
    s.push_str(&format!(
        "    if (start_cycle < 0) start_cycle = {start_cycle};\n"
    ));
    s.push_str(&format!("    if (ncycles < 0) ncycles = {fault_cycles};\n"));
    s.push_str("    bool known = false;\n");
    s.push_str("    for (int i = 0; i < N_TARGETS; i++) if (want == TARGETS[i]) known = true;\n");
    s.push_str("    if (!want.empty() && !known) {\n");
    s.push_str("        std::printf(\"WITNESS signal=%s status=unknown-signal\\n\", want.c_str());\n");
    s.push_str("        return 0;\n");
    s.push_str("    }\n");
    s.push_str(&format!("    {model}* tb = new {model};\n"));
    let port_bases: Vec<String> = observables
        .iter()
        .filter_map(|o| o.strip_prefix("PORT:").map(|x| x.to_string()))
        .collect();

    if !port_bases.is_empty() {
        s.push_str("    if (contract) {\n");
        s.push_str("        bool ok_err = false, ok_act = false;\n");
        for b in &port_bases {
            s.push_str(&format!(
                "        if (cport_err == \"obs_{b}_g\") ok_err = true;\n"
            ));
        }
        for b in &port_bases {
            s.push_str(&format!(
                "        if (cport_act == \"obs_{b}_g\") ok_act = true;\n"
            ));
        }
        s.push_str("        if (!ok_err || !ok_act) {\n");
        s.push_str("            std::printf(\"CONTRACT status=unknown-port error_port=%s action_port=%s valid=0\\n\", cport_err.c_str(), cport_act.c_str());\n");
        s.push_str("            delete tb; return 0;\n");
        s.push_str("        }\n");
        s.push_str("    }\n");
    }

    s.push_str("    bool diverged = false, reported = false;\n");
    s.push_str("    const long long MAXC = 2000000;\n");
    s.push_str("    long long applied = 0;\n");
    s.push_str("    std::set<unsigned long long> seen;\n");
    s.push_str("    long long changes = 0;\n");
    s.push_str("    unsigned long long prev = 0;\n");
    s.push_str("    bool first = true;\n");
    s.push_str("    bool force_effective = false;\n");
    s.push_str("    bool err_seen = false, act_moved = false, act_first = true;\n");
    s.push_str("    unsigned long long prev_act = 0;\n");
    s.push_str("    bool inwin_prev = false;\n");

    // Internal state is reached through the DUT instance inside the
    // testbench, which is how the per-signal public_flat_rw metacomments
    // expose it. Forcing is applied twice per cycle: Verilator evaluates
    // seq-then-comb, so a value written after an eval is captured by the
    // register at the following edge, and re-applying it stops the comb
    // logic clobbering it first.
    s.push_str(&format!(
        "    auto* d_fault = tb->rootp->__PVT__{tb_top}__DOT__u_fault;\n"
    ));
    s.push_str(&format!(
        "    auto* d_golden = tb->rootp->__PVT__{tb_top}__DOT__u_golden;\n"
    ));
    s.push_str("    auto do_force = [&]() {\n");
    s.push_str("        if (want.empty()) return;\n");
    for (name, member) in targets {
        if member != name {
            // Force-mux form. The net itself never becomes an addressable
            // member (Verilator folds nets into their consumers), so the patcher
            // rewrote its driver as `sel ? val : expr` over two public
            // *variables*. Drive both halves: select the injected value, and
            // zero it (stuck-at-0).
            let sel = member.replace("rtlsec_fi_val_", "rtlsec_fi_sel_");
            s.push_str(&format!(
                "        if (want == \"{name}\") {{ d_fault->{sel} = 1; std::memset(&d_fault->{member}, 0, sizeof(d_fault->{member})); }}\n"
            ));
        } else {
            // memset rather than `= 0`: internal signals may be scalars, enums,
            // VlWide<N> or WData[] arrays, and plain assignment does not compile
            // for the wide forms. Zeroing the storage is valid for all of them.
            s.push_str(&format!(
                "        if (want == \"{name}\") {{ std::memset(&d_fault->{member}, 0, sizeof(d_fault->{member})); }}\n"
            ));
        }
    }
    s.push_str("    };\n");

    s.push_str("    for (long long c = 0; c < MAXC && !Verilated::gotFinish(); c++) {\n");
    s.push_str("        tb->clk = 0; tb->eval();\n");
    s.push_str("        if (inwin_prev) {\n");
    for (name, member) in targets {
        if member != name {
            // Force-mux form: the original net is not a member, so effectiveness
            // is evidenced by the selector actually being driven (golden leaves
            // it 0, the fault instance selects the injected value). Whether the
            // injection changes behaviour is measured separately, against the
            // observables.
            let sel = member.replace("rtlsec_fi_val_", "rtlsec_fi_sel_");
            s.push_str(&format!(
                "            if (want == \"{name}\") {{ if (d_golden->{sel} != d_fault->{sel}) force_effective = true; }}\n"
            ));
        } else {
            s.push_str(&format!(
                "            if (want == \"{name}\") {{ if (std::memcmp(&d_golden->{member}, &d_fault->{member}, sizeof(d_golden->{member})) != 0) force_effective = true; }}\n"
            ));
        }
    }
    s.push_str("        }\n");
    s.push_str("        bool inwin = !want.empty() && c >= start_cycle && applied < ncycles;\n");
    s.push_str("        if (inwin) { do_force(); applied++; }\n");
    s.push_str("        tb->clk = 1; tb->eval();\n");
    s.push_str("        if (inwin) { do_force(); }\n");
    s.push_str("        {\n");
    // memcmp rather than != : observable members may be scalars, enums, VlWide
    // or WData[] arrays, and not all of those support operator!=.
    //
    // Only members of at most 8 bytes are compared. Larger members are structs
    // or wide vectors whose unused high words and padding bytes are not
    // meaningful, so memcmp reports differences that do not exist — comparing
    // them produced a divergence for every fault, including on pure inputs that
    // both instances receive identically. Scalars (error flags, valid/ready,
    // state, enable lines) are exact and are what the oracle needs.
    for o in &obs {
        match o.strip_prefix("PORT:") {
            Some(base) => s.push_str(&format!(
                "            if (std::memcmp(&tb->obs_{base}_g, &tb->obs_{base}_f, sizeof(tb->obs_{base}_g)) != 0) diverged = true;\n"
            )),
            None => s.push_str(&format!(
                "            if (sizeof(d_golden->{o}) <= 8 && std::memcmp(&d_golden->{o}, &d_fault->{o}, sizeof(d_golden->{o})) != 0) diverged = true;\n"
            )),
        }
    }
    for d in &det {
        match d.strip_prefix("PORT:") {
            Some(base) => s.push_str(&format!(
                "            if (std::memcmp(&tb->obs_{base}_g, &tb->obs_{base}_f, sizeof(tb->obs_{base}_g)) != 0) reported = true;\n"
            )),
            None => s.push_str(&format!(
                "            if (sizeof(d_golden->{d}) <= 8 && std::memcmp(&d_golden->{d}, &d_fault->{d}, sizeof(d_golden->{d})) != 0) reported = true;\n"
            )),
        }
    }
    // Generic activity probe over the golden instance: hash the observable
    // vector every cycle. A null sweep only means anything if this shows the
    // design is moving; otherwise the module is parked and the result is a
    // false negative, not a clean design.
    s.push_str("            unsigned long long h = 1469598103934665603ULL;\n");
    for o in &obs {
        match o.strip_prefix("PORT:") {
            Some(base) => s.push_str(&format!(
                "            {{ const unsigned char* p = (const unsigned char*)&tb->obs_{base}_g; for (size_t i = 0; i < sizeof(tb->obs_{base}_g); i++) {{ h ^= p[i]; h *= 1099511628211ULL; }} }}\n"
            )),
            None => s.push_str(&format!(
                "            if (sizeof(d_golden->{o}) <= 8) {{ const unsigned char* p = (const unsigned char*)&d_golden->{o}; for (size_t i = 0; i < sizeof(d_golden->{o}); i++) {{ h ^= p[i]; h *= 1099511628211ULL; }} }}\n"
            )),
        }
    }
    s.push_str("            seen.insert(h);\n");
    s.push_str("            if (!first && h != prev) changes++;\n");
    s.push_str("            prev = h; first = false;\n");
    s.push_str("        }\n");
    // Contract check: the design's own error signal asserting while a guarded
    // action still advances is a self-contradiction - the missing-gate defect.
    // No injected fault is involved, which is exactly why fault injection
    // cannot see this class.
    for b in &port_bases {
        s.push_str(&format!(
            "        if (contract && cport_err == \"obs_{b}_g\") {{ if (tb->obs_{b}_g) err_seen = true; }}\n"
        ));
    }
    for b in &port_bases {
        s.push_str(&format!(
            "        if (contract && cport_act == \"obs_{b}_g\") {{ unsigned long long h = 1469598103934665603ULL; const unsigned char* p = (const unsigned char*)&tb->obs_{b}_g; for (size_t i = 0; i < sizeof(tb->obs_{b}_g); i++) {{ h ^= p[i]; h *= 1099511628211ULL; }} if (!act_first && h != prev_act) act_moved = true; prev_act = h; act_first = false; }}\n"
        ));
    }
    s.push_str("        inwin_prev = inwin;\n");
    s.push_str("    }\n");

    s.push_str("    if (probe) std::printf(\"ACTIVITY golden distinct_vectors=%zu changes=%lld\\n\", seen.size(), changes);\n");
    s.push_str("    std::printf(\"WITNESS signal=%s fault=stuck-at-0 start=%ld for=%lld diverged=%d reported=%d force_effective=%d\\n\",\n");
    s.push_str("                want.empty() ? \"(golden)\" : want.c_str(), start_cycle, applied,\n");
    s.push_str("                diverged ? 1 : 0, reported ? 1 : 0, force_effective ? 1 : 0);\n");
    s.push_str("    if (contract)\n");
    s.push_str("        std::printf(\"CONTRACT error_port=%s action_port=%s error_asserted=%d action_advanced=%d contradiction=%d\\n\",\n");
    s.push_str("                    cport_err.c_str(), cport_act.c_str(), err_seen ? 1 : 0, act_moved ? 1 : 0, (err_seen && act_moved) ? 1 : 0);\n");
    s.push_str("    if (!want.empty() && diverged && !reported)\n");
    s.push_str("        std::printf(\"FINDING silent-divergence signal=%s fault=stuck-at-0 start=%ld\\n\",\n");
    s.push_str("                    want.c_str(), start_cycle);\n");
    s.push_str("    else if (want.empty())\n");
    s.push_str("        std::printf(\"GOLDEN ok diverged=%d reported=%d\\n\", diverged ? 1 : 0, reported ? 1 : 0);\n");
    s.push_str("    else\n");
    s.push_str("        std::printf(\"NOHIT signal=%s diverged=%d reported=%d\\n\", want.c_str(), diverged ? 1 : 0, reported ? 1 : 0);\n");
    s.push_str("    delete tb;\n    return 0;\n}\n");
    s
}

