/// Observables as declared by the harness testbench: every `obs_<name>_g`
/// output port, in order of appearance.
///
/// The harness is the authority on what the oracle compares, not the module's
/// own port list. Module-level derivation keeps only "simple" ports, so a wide
/// bus a testbench deliberately exposes (512-bit state, a seed vector) would be
/// invisible to the oracle and any check keyed on it would never fire.
pub fn tb_observables(tb_text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut i = 0usize;
    while let Some(rel) = tb_text[i..].find("obs_") {
        let start = i + rel + 4;
        let mut end = start;
        let bytes = tb_text.as_bytes();
        while end < bytes.len() && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_') {
            end += 1;
        }
        if let Some(base) = tb_text[start..end].strip_suffix("_g") {
            // Only paired ports are observables: the oracle compares the golden
            // and fault instances through obs_<base>_g / obs_<base>_f. A lone
            // _g port is for single-run checks, not a differential.
            let paired = format!("obs_{base}_f");
            if !base.is_empty()
                && tb_text.contains(&paired)
                && !out.iter().any(|x| x == base)
            {
                out.push(base.to_string());
            }
        }
        i = if end > start { end } else { start };
    }
    out
}
