//! harness.rs — generate a Verilator testbench that drives an IP top over its
//! real TL-UL bus.
//!
//! The harness is produced from the IP's own module header: every input port
//! other than clock/reset/TL-UL is tied off, and the bus is driven by the
//! in-tree `tlul_adapter_host`, which generates protocol-correct TL-UL
//! including the integrity fields the design checks.
//!
//! A campaign is a list of commands the testbench replays:
//!   op 0 = write(addr, data), op 1 = read(addr), op 2 = idle(data cycles)
//! Commands are read with `$readmemh` (three hex tokens per command) and the
//! responses are written to a trace file for the caller to score.

use crate::surface::Surface;
use regex::Regex;
use std::fmt::Write as _;
use std::path::Path;

#[derive(Debug, Clone, PartialEq)]
pub enum Dir {
    In,
    Out,
    InOut,
}

#[derive(Debug, Clone)]
pub struct Port {
    pub dir: Dir,
    pub name: String,
    /// Declared type text, e.g. `tlul_pkg::tl_h2d_t`, `logic [3:0]`, `mubi8_t`.
    pub ty: String,
}

impl Port {
    pub fn is_tl(&self) -> bool {
        self.name == "tl_i" || self.name == "tl_o"
    }
    pub fn is_clock_or_reset(&self) -> bool {
        matches!(self.name.as_str(), "clk_i" | "rst_ni" | "rst_shadowed_ni")
    }
}

/// Parse the port list of `module <ip>` from its source file.
pub fn parse_ports(src: &str, ip: &str) -> Result<Vec<Port>, String> {
    let start = src
        .find(&format!("module {ip}"))
        .ok_or_else(|| format!("module {ip} not found"))?;
    let rest = &src[start..];
    // The header ends at the first `);` that closes the port list.
    let end = rest
        .find(");")
        .ok_or_else(|| format!("port list for {ip} not terminated"))?;
    let header = &rest[..end];

    // Ports may be typed (`input tlul_pkg::tl_h2d_t tl_i`) or untyped
    // (`input clk_i`), so the type group is optional and defaults to `logic`.
    let re = Regex::new(
        r"(?s)\b(input|output|inout)\b\s+(?:([A-Za-z_][\w:]*(?:\s*\[[^\]]*\])?)\s+)?([A-Za-z_]\w*)\s*(?:,|$)",
    )
    .expect("port regex");

    let mut ports = Vec::new();
    for c in re.captures_iter(header) {
        let dir = match &c[1] {
            "input" => Dir::In,
            "output" => Dir::Out,
            _ => Dir::InOut,
        };
        let ty = c
            .get(2)
            .map(|m| m.as_str().split_whitespace().collect::<Vec<_>>().join(" "))
            .unwrap_or_else(|| "logic".to_string());
        let name = c[3].to_string();
        if name == "module" || name == ip {
            continue;
        }
        ports.push(Port { dir, name, ty });
    }
    if ports.is_empty() {
        return Err(format!("no ports parsed for {ip}"));
    }
    Ok(ports)
}

pub struct Harness {
    pub tb: String,
    pub filelist: String,
    pub ip: String,
}

fn tb_common_header(ip: &str, ports: &[Port]) -> String {
    let mut s = String::new();
    let _ = write!(
        s,
        r#"// Generated by rtlsec — live bus attack harness for `{ip}`.
// Do not edit by hand; regenerate with `rtlsec harness`.
`timescale 1ns/1ps
module tb_{ip} (
  input logic clk
);
  import tlul_pkg::*;
  import prim_mubi_pkg::*;

  logic rst_n = 1'b0;

  // Cycle counter doubles as a watchdog so a wedged design cannot hang the
  // campaign. The clock itself is driven by the C++ simulation main, which is
  // how Verilator 4.x expects a top-level clock.
  int unsigned cyc = 0;
  int unsigned CYCLES = 400000;
  always @(posedge clk) begin
    cyc <= cyc + 1;
    if (cyc > CYCLES) begin
      $display("RTLSEC_TIMEOUT cycles=%0d", cyc);
      $finish;
    end
  end

  // ---- host request interface into tlul_adapter_host ----
  logic        req = 1'b0, we = 1'b0;
  logic        gnt, valid, err, intg_err;
  logic [31:0] addr = 32'h0, wdata = 32'h0, rdata;
  logic [3:0]  be = 4'h0;

  tl_h2d_t tl_h2d;
  tl_d2h_t tl_d2h;

  tlul_adapter_host #(
    .MAX_REQS(1),
    .EnableDataIntgGen(1),
    .EnableRspDataIntgCheck(1)
  ) u_adapter (
    .clk_i         (clk),
    .rst_ni        (rst_n),
    .req_i         (req),
    .gnt_o         (gnt),
    .addr_i        (addr),
    .we_i          (we),
    .wdata_i       (wdata),
    .wdata_intg_i  ('0),
    .be_i          (be),
    .instr_type_i  (MuBi4False),
    .user_rsvd_i   ('0),
    .valid_o       (valid),
    .rdata_o       (rdata),
    .rdata_intg_o  (),
    .err_o         (err),
    .intg_err_o    (intg_err),
    .tl_o          (tl_h2d),
    .tl_i          (tl_d2h)
  );

  // ---- device under test: the real IP top ----
  {ip} u_dut (
"#
    );

    let mut conns: Vec<String> = Vec::new();
    for p in ports {
        if p.is_clock_or_reset() {
            let conn = if p.name == "clk_i" { "clk" } else { "rst_n" };
            conns.push(format!(".{0}({conn})", p.name));
        } else if p.name == "tl_i" {
            conns.push(".tl_i(tl_h2d)".to_string());
        } else if p.name == "tl_o" {
            conns.push(".tl_o(tl_d2h)".to_string());
        } else if p.dir == Dir::In {
            // Tie-off: most IP inputs are unused by a bus attack. Zero is the
            // canonical "inactive" value for the mubi/boolean/struct types used.
            conns.push(format!(".{0}('0)", p.name));
        } else {
            conns.push(format!(".{0}()", p.name));
        }
    }
    s.push_str(&conns.join(",\n    "));
    s.push_str("\n  );\n");
    s
}

fn tb_driver(_ip: &str, ports: &[Port]) -> String {
    let mut obs_w = String::new();
    let mut obs_r = String::new();
    for p in ports.iter().filter(|p| p.dir == Dir::Out && !p.is_tl()) {
        let _ = writeln!(
            obs_w,
            "          $fdisplay(fd_r, \"OBS {0} %h\", u_dut.{0});",
            p.name
        );
        let _ = writeln!(
            obs_r,
            "          $fdisplay(fd_r, \"OBS {0} %h\", u_dut.{0});",
            p.name
        );
    }

    // Verilator 4.x rejects timing controls nested inside tasks or loops (that
    // requires 5.x `--timing`), so the campaign is driven by a clocked state
    // machine with a single `@(posedge clk)` per block.
    format!(
        r#"
  // ---- campaign driver (clocked FSM) ----
  integer fd_c, fd_r;
  int unsigned cmds [0:3*4096-1];
  int unsigned ncmd   = 0;
  int unsigned idx    = 0;
  int unsigned rstcnt = 0;
  int unsigned idlect = 0;
  int unsigned op_cur = 0;

  typedef enum logic [2:0] {{
    ST_RESET, ST_FETCH, ST_REQ, ST_RESP, ST_IDLE, ST_FINISH
  }} st_e;
  st_e st = ST_RESET;

  initial begin
    fd_c = $fopen("cmds.hex", "r");
    if (fd_c == 0) begin
      $display("RTLSEC_FATAL missing cmds.hex");
      $fatal(1, "missing cmds.hex");
    end
    $fclose(fd_c);
    $readmemh("cmds.hex", cmds);
    // Commands run until the writer's sentinel address (0xdead_beef).
    while (ncmd < 4096 && cmds[3*ncmd + 1] != 32'hdead_beef) begin
      ncmd = ncmd + 1;
    end
    fd_r = $fopen("resp.txt", "w");
    if (fd_r == 0) begin
      $display("RTLSEC_FATAL cannot open resp.txt");
      $fatal(1, "cannot open resp.txt");
    end
  end

  always @(posedge clk) begin
    case (st)
      ST_RESET: begin
        rstcnt <= rstcnt + 1;
        if (rstcnt >= 16) begin
          rst_n <= 1'b1;
          st <= ST_FETCH;
        end
      end

      ST_FETCH: begin
        if (idx >= ncmd) begin
          st <= ST_FINISH;
        end else begin
          op_cur <= cmds[3*idx + 0];
          addr   <= cmds[3*idx + 1];
          wdata  <= cmds[3*idx + 2];
          be     <= 4'hf;
          if (cmds[3*idx + 0] == 0) begin
            we <= 1'b1; req <= 1'b1; st <= ST_REQ;      // write
          end else if (cmds[3*idx + 0] == 1) begin
            we <= 1'b0; req <= 1'b1; st <= ST_REQ;      // read
          end else begin
            idlect <= cmds[3*idx + 2];                  // idle N cycles
            st <= ST_IDLE;
          end
        end
      end

      ST_REQ: begin
        if (gnt) begin
          req <= 1'b0;
          st  <= ST_RESP;
        end
      end

      ST_RESP: begin
        if (valid) begin
          if (op_cur == 0) begin
            $fdisplay(fd_r, "W %h %h err=%0d intg=%0d", addr, wdata, err, intg_err);
{obs_w}          end else begin
            $fdisplay(fd_r, "R %h %h err=%0d intg=%0d", addr, rdata, err, intg_err);
{obs_r}          end
          idx <= idx + 1;
          st  <= ST_FETCH;
        end
      end

      ST_IDLE: begin
        if (idlect == 0) begin
          idx <= idx + 1;
          st  <= ST_FETCH;
        end else begin
          idlect <= idlect - 1;
        end
      end

      ST_FINISH: begin
        $display("RTLSEC_DONE commands=%0d cycles=%0d", ncmd, cyc);
        $fclose(fd_r);
        $finish;
      end

      default: st <= ST_RESET;
    endcase
  end

endmodule
"#,
        obs_w = obs_w,
        obs_r = obs_r
    )
}

/// Emit the testbench for the given IP top.
pub fn generate(surface: &Surface, top_src_path: &Path, top_src: &str) -> Result<Harness, String> {
    let ports = parse_ports(top_src, &surface.ip)?;
    if !ports.iter().any(|p| p.is_tl()) {
        return Err(format!(
            "{}: no tl_i/tl_o ports found; not a TL-UL peripheral top",
            surface.ip
        ));
    }
    let mut tb = tb_common_header(&surface.ip, &ports);
    tb.push_str(&tb_driver(&surface.ip, &ports));

    let filelist = format!(
        "# Generated by rtlsec for {ip}\n{}
",
        top_src_path.display(),
        ip = surface.ip
    );
    Ok(Harness {
        tb,
        filelist,
        ip: surface.ip.clone(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_typed_ports() {
        let src = r#"
module entropy_src
  import entropy_src_pkg::*;
(
  input clk_i,
  input rst_ni,
  input  tlul_pkg::tl_h2d_t tl_i,
  output tlul_pkg::tl_d2h_t tl_o,
  input  mubi8_t otp_en_es_fw_read_i,
  output logic intr_es_fatal_err_o,
  input  logic [31:0] entropy_src_rng_bits_i
);
  logic unused;
endmodule
"#;
        let ports = parse_ports(src, "entropy_src").expect("parse");
        let names: Vec<&str> = ports.iter().map(|p| p.name.as_str()).collect();
        assert!(names.contains(&"tl_i"), "got {names:?}");
        assert!(names.contains(&"tl_o"));
        assert!(names.contains(&"otp_en_es_fw_read_i"));
        assert!(names.contains(&"entropy_src_rng_bits_i"));
        let tl_in = ports.iter().find(|p| p.name == "tl_i").unwrap();
        assert_eq!(tl_in.dir, Dir::In);
        assert!(tl_in.is_tl());
        let clk = ports.iter().find(|p| p.name == "clk_i").unwrap();
        assert!(clk.is_clock_or_reset());
    }
}
